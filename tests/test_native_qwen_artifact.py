"""Offline real wheel/RECORD/native archive closure; no ML imports or weights."""
import base64
import csv
import hashlib
import importlib.util
import io
from pathlib import Path
import re
import tempfile
import unittest
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('native_qwen_builder', ROOT/'scripts/build-native-qwen-wheel.py')
builder = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(builder)
UPSTREAM = ROOT/'requirements/upstream/qwen_tts-0.1.1-py3-none-any.whl'
WHEEL = ROOT/'requirements/wheels'/builder.FILENAME
SHA256 = '96e5d3dfdcf2a86bcb59d9a68de7ef51bd6f591a63cdae816a7c1da4cad31606'


class NativeQwenArtifactTests(unittest.TestCase):
    def test_offline_reproduction_exact_lock_and_changed_file_allowlist(self):
        with tempfile.TemporaryDirectory() as tmp:
            output=Path(tmp)/builder.FILENAME
            self.assertEqual(builder.build(UPSTREAM,output),SHA256)
            self.assertEqual(output.read_bytes(),WHEEL.read_bytes())
        lock=(ROOT/'requirements/qwen-macos-arm64.lock').read_text()
        self.assertNotRegex(lock,r'(?m)^qwen-tts==')
        self.assertFalse(lock.startswith('# This file was autogenerated'))
        self.assertIn('./requirements/wheels/'+builder.FILENAME+' \\\n    --hash=sha256:'+SHA256,lock)
        with zipfile.ZipFile(UPSTREAM) as original,zipfile.ZipFile(WHEEL) as patched:
            sox_users={n for n in patched.namelist() if n.endswith('.py') and
                       re.search(rb'\bsox\b',patched.read(n))}
            self.assertEqual(sox_users,{'qwen_tts/core/tokenizer_25hz/vq/speech_vq.py'})
            changed={n for n in original.namelist() if original.read(n)!=patched.read(n)}
            self.assertEqual(changed,{builder.CORE,builder.TOKENIZER,builder.DIST+'WHEEL',builder.DIST+'RECORD'})
            self.assertEqual(set(patched.namelist())-set(original.namelist()),{builder.DIST+'NOTICE'})
            self.assertEqual(original.read(builder.DIST+'METADATA'),patched.read(builder.DIST+'METADATA'))
            self.assertEqual(original.read(builder.DIST+'licenses/LICENSE'),patched.read(builder.DIST+'licenses/LICENSE'))
            for name in (builder.CORE,builder.TOKENIZER):
                self.assertTrue(patched.read(name).startswith(builder.MARK.encode()))
            records=list(csv.reader(io.StringIO(patched.read(builder.DIST+'RECORD').decode())))
            self.assertEqual({r[0] for r in records},set(patched.namelist()))
            for name,digest,size in records:
                if name.endswith('/RECORD'): continue
                raw=patched.read(name)
                self.assertEqual(int(size),len(raw))
                self.assertEqual(digest,'sha256='+base64.urlsafe_b64encode(hashlib.sha256(raw).digest()).rstrip(b'=').decode())

    def test_changed_upstream_is_refused_without_artifact(self):
        with tempfile.TemporaryDirectory() as tmp:
            altered=Path(tmp)/'upstream.whl';altered.write_bytes(UPSTREAM.read_bytes()+b'changed')
            output=Path(tmp)/builder.FILENAME
            with self.assertRaisesRegex(ValueError,'sha256_mismatch'):builder.build(altered,output)
            self.assertFalse(output.exists())

    def test_native_artifact_and_source_archive_closure(self):
        from service import native_package as package
        from packaging.utils import parse_wheel_filename
        lock=(ROOT/'requirements/qwen-macos-arm64.lock').read_text()
        pins=dict(re.findall(r'^([a-z0-9-]+)==([^\s]+)',lock,re.M))
        name,version,build,_=parse_wheel_filename(WHEEL.name)
        self.assertEqual(build,(1,'native12hz'))
        pins[str(name)]=str(version)
        package.wheel_identity(WHEEL,['qwen-tts'],pins)
        with tempfile.TemporaryDirectory() as tmp:
            archive=Path(tmp)/'native.zip';package.archive(archive)
            package.verify_archive(archive)
            with zipfile.ZipFile(archive) as source:
                self.assertEqual(source.read('native-worker/lib/tts.py'),(ROOT/'lib/tts.py').read_bytes())
                self.assertIn(b'_qwen_model_class()',source.read('native-worker/lib/tts.py'))
                self.assertIn('native-worker/docs/agent-interface/NATIVE-DEPENDENCY.md',source.namelist())
                # Native source archive deliberately carries no dependency wheels.
                self.assertFalse(any(n.endswith('.whl') for n in source.namelist()))


if __name__ == '__main__': unittest.main()
